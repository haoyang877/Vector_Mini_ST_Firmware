/* DS12589 Rev 6 与新版 ST LL 均为 30/130 ℃；仓库旧 LL 的 110 ℃ 不适用。 */
static float mcu_temperature_from_adc(uint32_t temperature_raw, uint32_t vref_raw,
    uint32_t cal_30, uint32_t cal_130, uint32_t vref_cal)
{
  float vdda_mv;
  float temperature_at_cal_vref;
  if (temperature_raw == 0U || temperature_raw >= 4095U ||
      vref_raw == 0U || vref_raw >= 4095U ||
      cal_30 == 0U || cal_130 >= 4095U || cal_130 <= cal_30 ||
      vref_cal == 0U || vref_cal >= 4095U)
  {
    return NAN;
  }
  vdda_mv = (float)vref_cal * (float)VREFINT_CAL_VREF / (float)vref_raw;
  if (vdda_mv < 1620.0f || vdda_mv > 3600.0f)
  {
    return NAN;
  }
  temperature_at_cal_vref = (float)temperature_raw * vdda_mv /
      (float)TEMPSENSOR_CAL_VREFANALOG;
  return 30.0f + (temperature_at_cal_vref - (float)cal_30) * 100.0f /
      (float)(cal_130 - cal_30);
}

float motor_hw_mcu_temperature_c(void)
{
  uint32_t temperature_raw;
  uint32_t vref_raw;
  if ((ADC1->ISR & ADC_FLAG_JEOS) == 0U)
  {
    return NAN;
  }
  temperature_raw = ADC1->JDR1;
  vref_raw = ADC1->JDR2;
  /* 消费完整序列；不等待转换，未取得新采样时上层发布无效标记。 */
  __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_JEOS);
  return mcu_temperature_from_adc(temperature_raw, vref_raw,
      *TEMPSENSOR_CAL1_ADDR, *TEMPSENSOR_CAL2_ADDR, *VREFINT_CAL_ADDR);
}

