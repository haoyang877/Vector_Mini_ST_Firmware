#ifndef BOARD_PROFILE_DEFAULTS_H
#define BOARD_PROFILE_DEFAULTS_H

/* 板级编译契约：集中采样电路的固定输入，不包含设备地址、电机或应用整定。 */
#define FOC_HW_PROFILE_VECTOR_MINI_ST 1U
#ifndef FOC_ACTIVE_HW_PROFILE
#define FOC_ACTIVE_HW_PROFILE FOC_HW_PROFILE_VECTOR_MINI_ST
#endif

#if FOC_ACTIVE_HW_PROFILE == FOC_HW_PROFILE_VECTOR_MINI_ST

/* ADC额定输入：电流/VBUS换算不切换到温度通道测得的VDDA。 */
#define CURRENT_SENSE_PROFILE_ADC_REFERENCE_V 3.3f
#define CURRENT_SENSE_PROFILE_ADC_RESOLUTION_BITS 12U
#define CURRENT_SENSE_PROFILE_AMPLIFIER_GAIN 10.0f

/* 默认6mΩ；显式编译选项仍可选择已有的2mΩ配置。 */
#define CURRENT_SENSE_SHUNT_2_MILLIOHM 2U
#define CURRENT_SENSE_SHUNT_6_MILLIOHM 6U
#ifndef CURRENT_SENSE_SHUNT_MILLIOHM
#define CURRENT_SENSE_SHUNT_MILLIOHM CURRENT_SENSE_SHUNT_6_MILLIOHM
#endif

/* 母线分压电阻（kΩ）及ADC2每个rank的累加次数；须与实际ADC配置一致。 */
#define MOTOR_SENSING_VBUS_R1_KOHM 10.0f
#define MOTOR_SENSING_VBUS_R2_KOHM 1.0f
#define MOTOR_SENSING_ADC_SAMPLE_COUNT 4U

/* 初始中点不是实测零点；三相仍分别在启动采样后取得各自偏置。 */
#define PARAM_HW_CURRENT_OFFSET_A_COUNTS (1UL << (CURRENT_SENSE_PROFILE_ADC_RESOLUTION_BITS - 1U))
#define PARAM_HW_CURRENT_OFFSET_B_COUNTS (1UL << (CURRENT_SENSE_PROFILE_ADC_RESOLUTION_BITS - 1U))
#define PARAM_HW_CURRENT_OFFSET_C_COUNTS (1UL << (CURRENT_SENSE_PROFILE_ADC_RESOLUTION_BITS - 1U))

#if CURRENT_SENSE_SHUNT_MILLIOHM == CURRENT_SENSE_SHUNT_2_MILLIOHM
#define PARAM_HW_PHASE_RESISTANCE_PATH_COMPENSATION_OHM 0.004f
#elif CURRENT_SENSE_SHUNT_MILLIOHM == CURRENT_SENSE_SHUNT_6_MILLIOHM
#define PARAM_HW_PHASE_RESISTANCE_PATH_COMPENSATION_OHM 0.008f
#else
#error "Unsupported CURRENT_SENSE_SHUNT_MILLIOHM; select 2U or 6U"
#endif

#else
#error "Unsupported FOC_ACTIVE_HW_PROFILE"
#endif

#endif
