/**
 * @file mcu_resources.h
 * @brief AT32F456板级资源分配；仅供本MCU的BSP实现使用。
 * @note 改资源时成组核对GPIO/复用/外设时钟、通道/结果寄存器、触发和IRQ。
 *       此处不初始化硬件，不改变板卡能力或应用策略。SDK符号在使用处解析。
 *       时钟频率、模拟比例和Flash布局沿用board_config.h，不重复维护数值。
 */
#ifndef AT32F456_MCU_RESOURCES_H
#define AT32F456_MCU_RESOURCES_H

#include "board_config.h"

#if BSP_BOARD != BSP_BOARD_AT32F456
#error "AT32F456 resources require the AT32F456 board"
#endif

/* PWM：A/B/C = TMR1 CH2/3/4；上桥PA9/10/11，下桥PB0/1/4，均AF1。
 * 同组引脚共用端口；跨端口拆分时同步调整pwm.c中的GPIO分组初始化。
 * 通道、比较寄存器、输出使能位必须一并修改；CH1留给ADC触发，无外部输出。 */
#define MCU_PWM_TIMER TMR1
#define MCU_PWM_CLOCK CRM_TMR1_PERIPH_CLOCK
#define MCU_PWM_PHASE_A_CHANNEL TMR_SELECT_CHANNEL_2
#define MCU_PWM_PHASE_B_CHANNEL TMR_SELECT_CHANNEL_3
#define MCU_PWM_PHASE_C_CHANNEL TMR_SELECT_CHANNEL_4
#define MCU_PWM_PHASE_A_COMPARE (MCU_PWM_TIMER->c2dt)
#define MCU_PWM_PHASE_B_COMPARE (MCU_PWM_TIMER->c3dt)
#define MCU_PWM_PHASE_C_COMPARE (MCU_PWM_TIMER->c4dt)
#define MCU_PWM_PHASE_CHANNEL_MASK 0x5550U
#define MCU_PWM_MASTER_ENABLE_MASK 0x8000U
#define MCU_PWM_HIGH_PORT GPIOA
#define MCU_PWM_HIGH_CLOCK CRM_GPIOA_PERIPH_CLOCK
#define MCU_PWM_LOW_PORT GPIOB
#define MCU_PWM_LOW_CLOCK CRM_GPIOB_PERIPH_CLOCK
#define MCU_PWM_A_HIGH_PIN GPIO_PINS_9
#define MCU_PWM_B_HIGH_PIN GPIO_PINS_10
#define MCU_PWM_C_HIGH_PIN GPIO_PINS_11
#define MCU_PWM_A_LOW_PIN GPIO_PINS_0
#define MCU_PWM_B_LOW_PIN GPIO_PINS_1
#define MCU_PWM_C_LOW_PIN GPIO_PINS_4
#define MCU_PWM_A_HIGH_SOURCE GPIO_PINS_SOURCE9
#define MCU_PWM_B_HIGH_SOURCE GPIO_PINS_SOURCE10
#define MCU_PWM_C_HIGH_SOURCE GPIO_PINS_SOURCE11
#define MCU_PWM_A_LOW_SOURCE GPIO_PINS_SOURCE0
#define MCU_PWM_B_LOW_SOURCE GPIO_PINS_SOURCE1
#define MCU_PWM_C_LOW_SOURCE GPIO_PINS_SOURCE4
#define MCU_PWM_GPIO_AF GPIO_MUX_1

/* 定时器：TMR1负责20kHz载波/快速ADC触发，TMR6负责2kHz监督和ADC2普通组NTC采样。
 * 频率由FOC_FREQ/SUPERVISOR_FREQ及AT32_TIMER_HZ计算，不另存周期常量。 */
#define MCU_CONTROL_TIMER TMR6
#define MCU_CONTROL_TIMER_CLOCK CRM_TMR6_PERIPH_CLOCK
#define MCU_ADC_TRIGGER_TIMER MCU_PWM_TIMER
#define MCU_ADC_TRIGGER_CHANNEL TMR_SELECT_CHANNEL_1
#define MCU_ADC_TRIGGER_OUTPUT TMR_PRIMARY_SEL_C1ORAW
#define MCU_ADC_FAST_TRIGGER ADC_PREEMPT_TRIG_TMR1TRGOUT
#define MCU_ADC_SLOW_TRIGGER ADC_ORDINARY_TRIG_TMR6TRGOUT

/* ADC1抢占序列：rank1/2/3 = 相A/相B/相C，4次和域。
 * 输入通道和转换结果槽分别配置；调整rank时同步调整pdt槽。所有外部模拟量在GPIOA。 */
#define MCU_ADC_GPIO_PORT GPIOA
#define MCU_ADC_GPIO_CLOCK CRM_GPIOA_PERIPH_CLOCK
#define MCU_ADC_FAST ADC1
#define MCU_ADC_FAST_CLOCK CRM_ADC1_PERIPH_CLOCK
#define MCU_ADC_PHASE_A_PIN GPIO_PINS_0
#define MCU_ADC_PHASE_B_PIN GPIO_PINS_1
#define MCU_ADC_PHASE_C_PIN GPIO_PINS_2
#define MCU_ADC_BUS_VOLTAGE_PIN GPIO_PINS_3
#define MCU_ADC_PHASE_A_CHANNEL ADC_CHANNEL_0
#define MCU_ADC_PHASE_B_CHANNEL ADC_CHANNEL_1
#define MCU_ADC_PHASE_C_CHANNEL ADC_CHANNEL_2
#define MCU_ADC_BUS_VOLTAGE_CHANNEL ADC_CHANNEL_3
#define MCU_ADC_PHASE_A_RESULT (MCU_ADC_FAST->pdt1)
#define MCU_ADC_PHASE_B_RESULT (MCU_ADC_FAST->pdt2)
#define MCU_ADC_PHASE_C_RESULT (MCU_ADC_FAST->pdt3)

/* ADC2抢占序列：PA4母线电流、PA5/6输出sin/cos、PA3母线电压，均为12位单次采样。
 * ADC2普通序列只采PA7电机NTC，单次结果保存在odt。 */
#define MCU_ADC_AUX ADC2
#define MCU_ADC_AUX_CLOCK CRM_ADC2_PERIPH_CLOCK
#define MCU_ADC_BUS_CURRENT_PIN GPIO_PINS_4
#define MCU_ADC_BUS_CURRENT_CHANNEL ADC_CHANNEL_4
#define MCU_ADC_BUS_CURRENT_RESULT (MCU_ADC_AUX->pdt1)
#define MCU_ADC_MOTOR_TEMPERATURE_PIN GPIO_PINS_7
#define MCU_ADC_MOTOR_TEMPERATURE_CHANNEL ADC_CHANNEL_7
#define MCU_ADC_LINEAR_HALL_SIN_PIN GPIO_PINS_5
#define MCU_ADC_LINEAR_HALL_COS_PIN GPIO_PINS_6
#define MCU_ADC_LINEAR_HALL_SIN_CHANNEL ADC_CHANNEL_5
#define MCU_ADC_LINEAR_HALL_COS_CHANNEL ADC_CHANNEL_6
#if BSP_ENABLED_BUS_CURRENT
#define MCU_ADC_LINEAR_HALL_SIN_RESULT (MCU_ADC_AUX->pdt2)
#define MCU_ADC_LINEAR_HALL_COS_RESULT (MCU_ADC_AUX->pdt3)
#else
#define MCU_ADC_LINEAR_HALL_SIN_RESULT (MCU_ADC_AUX->pdt1)
#define MCU_ADC_LINEAR_HALL_COS_RESULT (MCU_ADC_AUX->pdt2)
#endif
/* 母线电压始终占最后一个结果槽。 */
#define MCU_ADC_BUS_VOLTAGE_RANK (1U + BSP_ENABLED_BUS_CURRENT + 2U * BSP_ENABLED_LINEAR_HALL)
#if MCU_ADC_BUS_VOLTAGE_RANK == 4U
#define MCU_ADC_BUS_VOLTAGE_RESULT (MCU_ADC_AUX->pdt4)
#elif MCU_ADC_BUS_VOLTAGE_RANK == 3U
#define MCU_ADC_BUS_VOLTAGE_RESULT (MCU_ADC_AUX->pdt3)
#elif MCU_ADC_BUS_VOLTAGE_RANK == 2U
#define MCU_ADC_BUS_VOLTAGE_RESULT (MCU_ADC_AUX->pdt2)
#else
#define MCU_ADC_BUS_VOLTAGE_RESULT (MCU_ADC_AUX->pdt1)
#endif
#define MCU_ADC_MOTOR_TEMPERATURE_RESULT (MCU_ADC_AUX->odt)

/* 编码器SPI2：CS/SCK/MISO/MOSI = PB12/13/14/15，AF5。
 * CS由GPIO控制，同组引脚共用端口；主机16位、模式3、APB/32。
 * CS也在PWM初始化时预置高，避免上电误选；改CS后这两处共用同一配置。 */
#define MCU_ENCODER_SPI SPI2
#define MCU_ENCODER_SPI_CLOCK CRM_SPI2_PERIPH_CLOCK
#define BSP_ENCODER_GPIO_PORT GPIOB
#define BSP_ENCODER_GPIO_CLOCK CRM_GPIOB_PERIPH_CLOCK
#define BSP_ENCODER_CS_PIN 12U
#define BSP_ENCODER_SCK_PIN 13U
#define BSP_ENCODER_MISO_PIN 14U
#define BSP_ENCODER_MOSI_PIN 15U
#define BSP_ENCODER_GPIO_AF 5U

/* SPI DMA：DMA2 CH1接收、CH2发送，16位；轮询完成，不占用DMA中断。
 * CLEAR_MASK写DMA2清标志寄存器，覆盖CH1/2；换通道时必须一起修改。 */
#define MCU_ENCODER_DMA DMA2
#define MCU_ENCODER_DMA_CLOCK CRM_DMA2_PERIPH_CLOCK
#define MCU_ENCODER_RX_DMA_CHANNEL DMA2_CHANNEL1
#define MCU_ENCODER_TX_DMA_CHANNEL DMA2_CHANNEL2
#define MCU_ENCODER_RX_DMA_MUX DMA2MUX_CHANNEL1
#define MCU_ENCODER_TX_DMA_MUX DMA2MUX_CHANNEL2
#define MCU_ENCODER_RX_DMA_REQUEST DMAMUX_DMAREQ_ID_SPI2_RX
#define MCU_ENCODER_TX_DMA_REQUEST DMAMUX_DMAREQ_ID_SPI2_TX
#define MCU_ENCODER_DMA_CLEAR_MASK 0xFFU

/* CAN1：PB8 RX/PB9 TX，AF9；1M/5M位时序取board_config.h。 */
#define MCU_CAN CAN1
#define MCU_CAN_CLOCK CRM_CAN1_PERIPH_CLOCK
#define MCU_CAN_CLOCK_SELECT CRM_CAN1
#define MCU_CAN_GPIO_PORT GPIOB
#define MCU_CAN_GPIO_CLOCK CRM_GPIOB_PERIPH_CLOCK
#define MCU_CAN_RX_PIN GPIO_PINS_8
#define MCU_CAN_TX_PIN GPIO_PINS_9
#define MCU_CAN_RX_SOURCE GPIO_PINS_SOURCE8
#define MCU_CAN_TX_SOURCE GPIO_PINS_SOURCE9
#define MCU_CAN_GPIO_AF GPIO_MUX_9

/* 中断：数值越小优先级越高；控制临界区只屏蔽优先级>=2。
 * 外设、IRQn和本目录interrupt_map.h必须成组修改，不能只改NVIC编号。 */
#define MCU_ADC_IRQ ADC1_2_IRQn
#define MCU_ADC_IRQ_PRIORITY 0U
#define MCU_CONTROL_IRQ TMR6_DAC_GLOBAL_IRQn
#define MCU_CONTROL_IRQ_PRIORITY 2U
#define MCU_CAN_IRQ CAN1_RX_IRQn
#define MCU_CAN_IRQ_HANDLER CAN1_RX_IRQHandler
#define MCU_CAN_IRQ_PRIORITY 3U
#define MCU_SYSTICK_IRQ SysTick_IRQn
#define MCU_SYSTICK_IRQ_PRIORITY 3U
#define MCU_CONTROL_CRITICAL_PRIORITY 2U

/* UART：当前无驱动、无引脚/DMA/IRQ分配；接入时在此登记整组资源后实现初始化。
 * LED、外部编码器SPI和GPIO EXTI也未启用，不把预留焊盘当作已实现能力。 */

#endif
